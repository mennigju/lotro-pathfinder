-- Localized text; extra arguments are filled into %s
function Pathfinder.L(key, ...)
    local text = (Strings[Pathfinder.Lang] or Strings.en)[key] or Strings.de[key] or key
    if select("#", ...) > 0 then
        local args = { ... }
        for i = 1, #args do
            args[i] = tostring(args[i])
        end
        return string.format(text, unpack(args))
    end
    return text
end

-- "4,2" in German, "4.2" in English, whatever decimal point the client uses
function Pathfinder.FormatKm(meters)
    return (string.format("%.1f", meters / 1000):gsub("[%.,]", Pathfinder.Lang == "en" and "." or ","))
end

